HEAD = ["번호", "구분", "구성 요소", "무엇에 쓰는지", "공급처", "제조 단가에 포함?", "견적 단가", "부가세", "단가(V-)", "개당/1회", "개당 사용량·1회 횟수", "구매·MOQ 수량", "개당 금액", "첫 생산 남는 비용", "출처·견적일"]

def item_sheet(title, top, frag, rows):
    ws = wb.create_sheet(title)
    ws["A1"] = "표준 원가계산기 v7 (시험용 가짜 숫자)"
    labels = ["브랜드", "품목", "규격", "완제품 제조사", "생산 수량", "합계 포함", "차수"]
    for i, (lb, v) in enumerate(zip(labels, top)):
        ws.cell(row=5 + i, column=1, value=lb)
        ws.cell(row=5 + i, column=2, value=v)
    ws["D5"], ws["E5"] = "완제품 범위", frag["scope"]
    ws["D6"], ws["E6"] = "견적 유효기간", frag["valid"]
    ws["D7"], ws["E7"] = "향료 이름", frag["name"]
    ws["D8"], ws["E8"] = "향료 함유율", frag["ratio"]
    ws["F9"], ws["G9"] = "배합량 kg", frag["batch"]
    ws["I9"], ws["J9"] = "향료 kg 직접", frag["direct"]
    ws["D9"] = "향료 필요량"
    ws["E9"] = '=IF(J9<>"",J9,G9*E8)'
    for c, h in enumerate(HEAD, start=1):
        ws.cell(row=12, column=c, value=h)
    for i in range(20):
        r = 13 + i
        if i < len(rows):
            kind, name, use, sup, inc, price, vat, per, usage, moq, src = rows[i]
            vals = [i + 1, kind, name, use, sup, inc, price, vat, None, per, usage, moq, None, None, src]
            for c, v in enumerate(vals, start=1):
                if v is not None and v != "":
                    ws.cell(row=r, column=c, value=v)
        ws[f"I{r}"] = f'=IF(H{r}="V+",G{r}/1.1,G{r})'
        ws[f"M{r}"] = f'=IF($B$9=0,0,IF(J{r}="1회",I{r}*K{r}/$B$9,IF(F{r}="포함",0,I{r}*K{r})))'
        ws[f"N{r}"] = f'=IF(AND(J{r}="개당",L{r}<>""),MAX(L{r}-$B$9*K{r},0)*I{r},0)'
    ws["L34"], ws["M34"] = "완제품 기준 원가", "=SUM(M13:M32)"
    ws["L35"], ws["M35"] = "첫 생산 원가", '=IF($B$9=0,"",M34+SUM(N13:N32)/$B$9)'
    ws["L36"], ws["M36"] = "첫 생산 금액", '=IF($B$9=0,"",M35*$B$9)'
    return ws

